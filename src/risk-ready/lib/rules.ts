/**
 * PERSONALIZATION RULES — editable by non-engineers.
 *
 * Each rule reads the farm profile (farm type, enterprises, farm-adjacent businesses, assets,
 * people) and the protections inventory, and — when its `when` test is true — suggests one threat.
 *
 *   when        → the trigger. Use the helpers on `c`: c.has('grainBins'), c.hasEnterprise('corn'),
 *                 c.hasAdjacent('agritourism'), c.protection('cyber') === 'none', c.employees > 0 …
 *   because     → one short phrase shown to the farmer: "Because you …"
 *   threat      → the suggested threat with default probability (1–5) and severity (1–5)
 *   learn       → plain-language education blurb (2–3 sentences, no jargon)
 *   protection  → the protection that answers this threat. If the farmer marked it "don't have",
 *                 the threat is flagged "no protection in place" and ranked higher.
 *   actionGet   → recommended action when that protection is missing or unsure
 *   actionHave  → recommended action when they already HAVE it (usually a review with the agent)
 *   strategy    → optional override of the default category strategy
 *   resources   → record ids from /lib/catalog (programs, checklists, consultations, agtech, coverage)
 *   calculator  → optional inline insurance calculator for transfer decisions
 *
 * Nothing here is applied automatically: every suggestion is shown as a card the farmer
 * accepts, edits or dismisses.
 */
